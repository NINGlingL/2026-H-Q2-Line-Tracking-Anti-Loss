#define OLED_TIMEOUT_LOOPS 150000UL

static uint8_t g_oled_buffer[SSD1306_PAGES][SSD1306_WIDTH];

static bool wait_idle(void)
{
    uint32_t timeout = OLED_TIMEOUT_LOOPS;
    while ((DL_I2C_getControllerStatus(OLED_INST) &
            DL_I2C_CONTROLLER_STATUS_IDLE) == 0U) {
        if (--timeout == 0U) return false;
    }
    return true;
}

static bool write_byte(uint8_t control, uint8_t value)
{
    uint8_t tx[2] = {control, value};

    if (!wait_idle()) return false;
    DL_I2C_flushControllerTXFIFO(OLED_INST);
    if (DL_I2C_fillControllerTXFIFO(OLED_INST, tx, 2U) != 2U) {
        return false;
    }
    DL_I2C_startControllerTransfer(
        OLED_INST, SSD1306_I2C_ADDR,
        DL_I2C_CONTROLLER_DIRECTION_TX, 2U);
    return wait_idle();
}

static void command(uint8_t value)
{
    (void)write_byte(0x00U, value);
}

static void data(uint8_t value)
{
    (void)write_byte(0x40U, value);
}

void SSD1306_Clear(void)
{
    memset(g_oled_buffer, 0, sizeof(g_oled_buffer));
}

void SSD1306_Update(void)
{
    for (uint8_t page = 0U; page < SSD1306_PAGES; ++page) {
        command((uint8_t)(0xB0U + page));
        command(0x00U);
        command(0x10U);
        for (uint16_t column = 0U; column < SSD1306_WIDTH; ++column) {
            data(g_oled_buffer[page][column]);
        }
    }
}

void SSD1306_Init(void)
{
    static const uint8_t sequence[] = {
        0xAE, 0xD5, 0x80, 0xA8, 0x3F, 0xD3, 0x00, 0x40,
        0x8D, 0x14, 0x20, 0x02, 0xA1, 0xC8, 0xDA, 0x12,
        0x81, 0x7F, 0xD9, 0xF1, 0xDB, 0x40, 0xA4, 0xA6,
        0x2E, 0xAF
    };

    delay_cycles(CPUCLK_FREQ / 50U);
    for (uint32_t i = 0U; i < sizeof(sequence); ++i) {
        command(sequence[i]);
    }
    SSD1306_Clear();
    SSD1306_Update();
}

