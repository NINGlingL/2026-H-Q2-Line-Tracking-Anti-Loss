void SSD1306_ShowString(uint8_t page, uint8_t column, const char *text)
{
    if (text == 0) return;
    while (*text != '\0' && column <= (SSD1306_WIDTH - 6U)) {
        draw_char(page, column, *text++);
        g_oled_buffer[page][column + 5U] = 0U;
        column = (uint8_t)(column + 6U);
    }
}

void SSD1306_WriteFloat(uint8_t page, uint8_t column, float value,
                        uint8_t decimals)
{
    char text[20];
    int32_t integer;
    uint32_t fraction = 0U;
    uint32_t scale = 1U;
    uint8_t pos = 0U;

    if (decimals > 4U) decimals = 4U;
    if (value < 0.0f) {
        text[pos++] = '-';
        value = -value;
    }
    integer = (int32_t)value;
    if (integer == 0) {
        text[pos++] = '0';
    } else {
        char reverse[11];
        uint8_t count = 0U;
        while (integer > 0 && count < sizeof(reverse)) {
            reverse[count++] = (char)('0' + integer % 10);
            integer /= 10;
        }
        while (count > 0U) text[pos++] = reverse[--count];
    }
    if (decimals > 0U) {
        text[pos++] = '.';
        for (uint8_t i = 0U; i < decimals; ++i) scale *= 10U;
        fraction = (uint32_t)((value - (int32_t)value) * scale + 0.5f);
        for (uint8_t i = decimals; i > 0U; --i) {
            text[pos + i - 1U] = (char)('0' + fraction % 10U);
            fraction /= 10U;
        }
        pos = (uint8_t)(pos + decimals);
    }
    text[pos] = '\0';
    SSD1306_ShowString(page, column, text);
}
